// Builds pet-guests.js (and a copy next to the lab variants) from guests/merge-guests.json
// and guests/<slug>.js. Fails if a guest marked "live" has no look, or a look doesn't load.
//   node tools/build-guests.mjs
import fs from 'fs';
import { spawnSync } from 'child_process';
const CAT = JSON.parse(fs.readFileSync('guests/merge-guests.json', 'utf8'));
const live = CAT.guests.filter(g => g.live);
const missing = live.filter(g => !fs.existsSync(`guests/${g.id}.js`)).map(g => g.id);
if (missing.length) { console.error('live guests without a look:', missing.join(', ')); process.exit(1); }

const HH = 12 / Math.cos(0.38), swap = (rows, i, row) => { const c = rows.slice(); c[i] = row; return c; };
const parts = [];
for (const g of live) {
  const code = fs.readFileSync(`guests/${g.id}.js`, 'utf8').trim();
  const looks = {};
  new Function('ktGuest', code)((id, f) => { looks[id] = f; });          // each file must register itself and build
  if (typeof looks[g.id] !== 'function') { console.error(`${g.id}.js doesn't call ktGuest('${g.id}', ...)`); process.exit(1); }
  const look = looks[g.id]({ HH, STRANDS: [], swap, FACE: [] });
  if (!look || !look.ramps) { console.error(`${g.id}: the look has no ramps`); process.exit(1); }
  parts.push(code);
}
// every guest must draw in the studio (a look that throws or has a bad ramp would quietly stay out)
const trial = spawnSync(process.execPath, ['tools/guest-sheet.mjs', 'variants/big-hoodie.js', '--check', ...live.map(g => g.id)], { encoding: 'utf8' });
if (trial.status !== 0) { console.error(trial.stderr || trial.stdout); process.exit(1); }
const catalogue = {
  guests: live.map(({ id, name, company, live, episodes, pages }) => ({ id, name, company, live, episodes, pages })),
  episodes: Object.fromEntries(Object.entries(CAT.episodes).map(([id, e]) => [id, { tag: e.tag, guest: e.guest }]))
};
const out = `/* Henni's guests from The Merge, generated by tools/build-guests.mjs from
   guests/merge-guests.json and guests/*.js. pet.js loads this shortly before his
   podcast studio opens. Each guest is hand-sculpted from their episode; see guests/README.md. */
(function () {
  'use strict';
  var G = window.ktPetGuests || (window.ktPetGuests = {});
  G.looks = G.looks || {};
  function ktGuest(id, f) { G.looks[id] = f; }

${parts.join('\n\n')}

  G.catalogue = ${JSON.stringify(catalogue)};
})();
`;
fs.writeFileSync('pet-guests.js', out);
fs.writeFileSync('variants/pet-guests.js', out);
console.log(`pet-guests.js: ${live.length} guests, ${(out.length / 1024).toFixed(1)} KB`);
